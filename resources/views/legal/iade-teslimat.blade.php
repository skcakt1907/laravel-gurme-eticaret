<h4>Delivery</h4>
<ul>
    <li>Your orders are shipped to your address by our contracted courier once payment is confirmed.</li>
    <li>The shipping cost is shown in the cart and at checkout before you confirm the order.</li>
    <li>For bank transfer payments, preparation begins once the payment reaches our account.</li>
</ul>

<h4>Returns &amp; Right of Withdrawal</h4>
<ul>
    <li>You may exercise your right of withdrawal within <strong>14 days</strong> of receiving the product.</li>
    <li>The returned product must be unused, untried and in undamaged original packaging.</li>
    <li>You can send your return request to {{ setting('eposta') }} or call {{ setting('telefon') }}.</li>
    <li>Once the return is approved and the product reaches us, the amount is refunded via your payment method within 14 days.</li>
</ul>

<h4>Non-Returnable Products</h4>
<ul>
    <li>Foodstuffs whose packaging has been opened,</li>
    <li>Perishable products or those likely to pass their use-by date,</li>
    <li>Used or damaged products.</li>
</ul>

<h4>Damaged / Wrong Product</h4>
<p>If you notice damage to the parcel during delivery, we recommend having a report drawn up. If a wrong or damaged product is delivered, shipping and exchange costs are covered by us.</p>
